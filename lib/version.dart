/// هل الإصدار الحالي أقدم من `other`؟
///
/// بيقارن جزء جزء (`1.2.3`). أي جزء ناقص بيتحسب صفر، وأي صيغة
/// غريبة بترجع `false` — **التساهل مقصود**: إعداد غلط على السيرفر
/// مايصحّش يقفل الأبلكيشن على كل المناديب.
bool isOlder(String current, String other) {
  final a = _parts(current);
  final b = _parts(other);

  if (a.isEmpty || b.isEmpty) return false;

  for (var i = 0; i < 3; i++) {
    final x = i < a.length ? a[i] : 0;
    final y = i < b.length ? b[i] : 0;

    if (x != y) return x < y;
  }

  return false;
}

List<int> _parts(String v) {
  final m = RegExp(r'^\s*(\d+)(?:\.(\d+))?(?:\.(\d+))?').firstMatch(v.trim());

  if (m == null) return const [];

  return [
    int.parse(m.group(1)!),
    int.tryParse(m.group(2) ?? '0') ?? 0,
    int.tryParse(m.group(3) ?? '0') ?? 0,
  ];
}
